export function useBridgeCopy() {
  const [lang, setLang] = useState<string>(() => resolveBridgeLang());

  useEffect(() => {
    const refresh = () => setLang(resolveBridgeLang());
    const onStorage = (event: StorageEvent) => {
      if (!event.key || event.key === "pref_site_lang" || event.key === "gmx_site_lang" || event.key === "siteLang") refresh();
    };
    const onVisibility = () => refresh();
    window.addEventListener("storage", onStorage);
    window.addEventListener("focus", onVisibility);
    document.addEventListener("visibilitychange", onVisibility);
    return () => {
      window.removeEventListener("storage", onStorage);
      window.removeEventListener("focus", onVisibility);
      document.removeEventListener("visibilitychange", onVisibility);
    };
  }, []);

  const site = useMemo<CopyMap>(() => {
    const base = (SITE_I18N.en || {}) as CopyMap;
    const scoped = ((SITE_I18N as Record<string, CopyMap>)[lang] || {}) as CopyMap;
    return { ...base, ...scoped };
  }, [lang]);

  const bridge = useMemo<CopyMap>(() => {
    const base = BRIDGE_COPY.en || {};
    const scoped = BRIDGE_COPY[lang] || {};
    const extraBase = BRIDGE_COPY_EXTRA.en || {};
    const extraScoped = BRIDGE_COPY_EXTRA[lang] || {};
    return { ...base, ...scoped, ...extraBase, ...extraScoped };
  }, [lang]);

  const copy = useCallback((key: string, fallback = "") => {
    const value = bridge[key];
    return typeof value === "string" ? value : (fallback || key);
  }, [bridge]);

  const siteText = useCallback((key: string, fallback = "") => {
    const value = site[key];
    if (typeof value !== "string") return fallback;
    return value.startsWith("HTML:") ? value.slice(5) : value;
  }, [site]);

  return { lang, copy, siteText };
}


Object.keys(BRIDGE_COPY).forEach((lang) => {
  BRIDGE_COPY[lang] = { ...BRIDGE_COPY[lang], ...SHARED_SAFE_COPY };
});
