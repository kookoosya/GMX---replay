function normalizeLang(raw: unknown): string {
  const base = String(raw || "en").trim().toLowerCase().replace(/_/g, "-").split("-")[0] || "en";
  return Object.prototype.hasOwnProperty.call(SITE_I18N, base) ? base : "en";
}

function resolveBridgeLang(): string {
  if (typeof window === "undefined") return "en";
  try {
    const fromStorage = window.localStorage.getItem("pref_site_lang") || window.localStorage.getItem("gmx_site_lang") || window.localStorage.getItem("siteLang");
    if (fromStorage) return normalizeLang(fromStorage);
  } catch {
    // ignore
  }
  if (typeof document !== "undefined") {
    const docLang = document.documentElement.lang;
    if (docLang) return normalizeLang(docLang);
  }
  return normalizeLang(typeof navigator !== "undefined" ? navigator.language : "en");
}

